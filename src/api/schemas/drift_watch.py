"""
Pydantic v2 response schemas for the drift-watch read-only API.

These DTOs expose a curated view of ``DriftWatchInput`` and
``DriftWatchEpisode`` rows; they deliberately omit the raw spec/
calibration/state JSON blobs to avoid leaking internal model state.
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field


class DriftWatchInputResponse(BaseModel):
    """Public representation of one drift-watch input (monitor spec)."""

    model_config = ConfigDict(from_attributes=True)

    input_id: str
    """Stable identifier for this drift input (e.g. ``"hd_physics"``)."""

    kind: str
    """Residual strategy: ``paired_probes``, ``virtual_sensor``, or ``physics``."""

    target_channel: str
    """The sensor channel being monitored for drift."""

    status: str
    """Current calibration status: ``armed``, ``shadow``, ``derived``, or ``uncalibrated``."""

    status_reason: str
    """
    Human-readable explanation of the current status.

    - ``uncalibrated``: "awaiting N weeks of history"
    - ``shadow``: the shadow reason from the calibration run
    - ``derived``: describes the physics derivation
    - ``armed``: empty string (normal operation)
    """

    calibrated_at: Optional[datetime] = None
    """
    Approximate calibration timestamp.  ``None`` when ``status`` is
    ``uncalibrated``.  Uses ``updated_at`` as a proxy because no separate
    calibration timestamp is stored.
    """

    updated_at: datetime
    """Timestamp of the last row mutation (most recent upload)."""

    false_alarm_rate: Optional[float] = None
    """
    Measured false-alarm rate (alarms per month) on the calibration period.
    ``None`` when not yet calibrated.
    """

    detection_rate: Optional[float] = None
    """
    Minimum self-test detection rate across all injected fault scenarios.
    ``None`` when not yet calibrated.
    """

    greenhouse_id: str = "default"
    """Greenhouse the input belongs to."""

    alert_state: str = "off"
    """ADR-013 alert state: ``off``, ``eligible``, ``enabled`` or ``suspended``."""

    alert_state_reason: Optional[str] = None
    """Why the input is in ``alert_state`` (set on each transition)."""

    oos_count: Optional[int] = None
    """
    Out-of-sample false-alarm count in the trailing window (alert-eligible
    episodes without a ``confirmed_drift`` label). ``None`` when not scored.
    """

    raw_count: Optional[int] = None
    """All out-of-sample episodes in the trailing window; diagnosis only."""

    budget: int
    """Count at or below which an input may become eligible
    (``DRIFT_WATCH_ALERT_ENABLE_MAX_COUNT``)."""


class DriftWatchEpisodeResponse(BaseModel):
    """Public representation of one drift episode."""

    model_config = ConfigDict(from_attributes=True)

    input_id: str
    """The drift input that raised this episode."""

    episode_id: str
    """
    Stable episode identifier generated by the detector (e.g.
    ``"temp_paired_3"``).  The same episode_id is upserted across uploads
    so the row count does not inflate on repeated uploads of the same data.
    """

    target_channel: str
    """The sensor channel on which drift was detected."""

    direction: str
    """Direction of the drift: ``"+"`` (upward) or ``"-"`` (downward)."""

    first_detected_ts: datetime
    """Timestamp when the CUSUM threshold was first breached."""

    last_confirmed_ts: datetime
    """Timestamp of the most recent CUSUM alarm within this episode."""

    onset_estimate_ts: Optional[datetime] = None
    """Estimated physical onset of the drift (back-extrapolated), if available."""

    offset_estimate: Optional[float] = None
    """Estimated drift magnitude in native sensor units, if available."""

    peak_statistic: Optional[float] = None
    """Maximum CUSUM statistic reached during the episode."""

    input_status_at_detection: str
    """Status of the drift input when the episode was first detected."""

    ongoing: bool
    """
    ``True`` when the episode was confirmed within the last
    ``DRIFT_WATCH_QUIET_HOURS`` hours of the input's ``updated_at``,
    indicating the drift is still present in the most recent data.
    """

    armed: bool
    """
    ``True`` only when ``input_status_at_detection`` is ``"armed"``,
    distinguishing operationally significant episodes from shadow/informational
    ones.
    """

    offset_robust: Optional[float] = None
    """ADR-013 robust offset (signed, native units); ``None`` for old rows."""

    suppressed_by: Optional[str] = None
    """Detector that withheld the alert (e.g. ``stuck_fault``), if any."""

    label: Optional[str] = None
    """Operator label: ``confirmed_drift`` or ``false_alarm``; ``None`` if none."""

    alert_message: Optional[str] = None
    """ADR-013 §4 operator wording. Paired probes never name one probe."""


class DriftWatchFeedbackRequest(BaseModel):
    """Operator label on a drift episode, addressed by its natural key."""

    tenant_id: str = Field(min_length=1)
    greenhouse_id: str = Field(min_length=1)
    input_id: str = Field(min_length=1)
    direction: Literal["+", "-"]
    first_detected_ts: datetime
    label: Literal["confirmed_drift", "false_alarm"]
    note: Optional[str] = Field(default=None, max_length=2000)
    created_by: Optional[str] = Field(default=None, max_length=255)


class DriftWatchFeedbackResponse(BaseModel):
    """Stored label."""

    model_config = ConfigDict(from_attributes=True)

    tenant_id: str
    greenhouse_id: str
    input_id: str
    direction: str
    first_detected_ts: datetime
    label: str
    note: Optional[str] = None
    created_by: Optional[str] = None
    created_at: datetime
